export type TranslationKey = keyof typeof ru;
let language: TimeTrackerSettings['language'] = 'auto';

export function configureLanguage(value: TimeTrackerSettings['language']): void { language = value || 'auto'; }

export function getLocale(): 'ru' | 'en' {
    const selected = language === 'auto' ? getLanguage() : language;
    return selected?.toLowerCase().split(/[-_]/)[0] === 'ru' ? 'ru' : 'en';
}

export function t(key: TranslationKey, values: Record<string, string | number> = {}): string {
    const template: string = getLocale() === 'ru' ? ru[key] : key;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function formatDuration(minutes: number): string {
    const hours = Math.floor(Math.max(0, minutes) / 60);
    const remainder = Math.max(0, minutes) % 60;
    if (!hours) return t('{minutes}m', { minutes: remainder });
    if (!remainder) return t('{hours}h', { hours });
    return t('{hours}h {minutes}m', { hours, minutes: remainder });
}
